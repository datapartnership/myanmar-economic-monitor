// Function to create D3.js visualization
function createChart(damId) {
    console.log('Creating chart for:', damId);
    
    // Clear any existing chart
    d3.select("#" + damId + "-chart").selectAll("*").remove();
    
    const data = damData[damId];
    if (!data) {
        console.error(`No data found for dam: ${damId}`);
        return;
    }
    
    console.log('Data loaded for', damId, '- Date count:', data.data.dates.length);
    
    // Update metadata display
    const metadata = damMetadata[damId] || {};
    document.getElementById(damId + '-reported-start').textContent = metadata.reported_start || 'N/A';
    document.getElementById(damId + '-data-from').textContent = metadata.data_from || 'N/A';
    document.getElementById(damId + '-last-image').textContent = metadata.last_image || 'N/A';
    
    // Prepare data for D3
    const chartData = data.data.dates.map((date, i) => ({
        date: new Date(date),
        trend: data.data.trend[i],
        VV: data.data.VV[i],
        seasonal: data.data.seasonal[i]
    }));
    
    // Set dimensions and margins
    const container = document.getElementById(damId + '-chart');
    const parentContainer = container.parentElement;
    let containerWidth = container.clientWidth;
    
    // Fix for hidden tabs - use parent container width if container width is 0
    if (containerWidth === 0) {
        containerWidth = parentContainer ? parentContainer.clientWidth - 40 : 1320;
    }

    const margin = {top: 340, right: 30, bottom: 100, left: 150};
    // All images are same size - use fixed 4 images for consistent width across all dams
    const imgSize = 240;
    const spacing = 10;
    const numImages = 4; // Fixed to keep chart width consistent
    const totalImagesWidth = (imgSize * numImages) + (spacing * (numImages - 1)); // Always 990px
    const width = totalImagesWidth * 0.6; // 594px - squeeze chart to be smaller than images
    const svgWidth = totalImagesWidth + margin.left + margin.right; // SVG must be wide enough for images
    const height = 600 - margin.top - margin.bottom;
    // Center chart horizontally: offset so chart is centered within the SVG
    const chartOffsetX = margin.left + (totalImagesWidth - width) / 2;

    // Create SVG
    const svg = d3.select("#" + damId + "-chart")
        .append("svg")
        .attr("width", svgWidth)
        .attr("height", height + margin.top + margin.bottom)
        .append("g")
        .attr("transform", `translate(${chartOffsetX},${margin.top})`);
    
    console.log('SVG created with dimensions:', width + margin.left + margin.right, 'x', height + margin.top + margin.bottom);

    // Create scales
    const xExtent = d3.extent(chartData, d => d.date);
    const yMin = d3.min(chartData, d => d.trend) - 1;
    const yMax = d3.max(chartData, d => d.trend) + 1;
    
    // Extend x-axis to start from 2014
    const xStart = new Date('2014-01-01');
    const xEnd = xExtent[1];
    
    console.log('X domain:', [xStart, xEnd]);
    console.log('Y domain:', [yMin, yMax]);
    
    const x = d3.scaleTime()
        .domain([xStart, xEnd])
        .range([0, width]);

    const y = d3.scaleLinear()
        .domain([yMin, yMax])
        .range([height, 0]);
        
    // Create axes
    svg.append("g")
        .attr("transform", `translate(0,${height})`)
        .call(d3.axisBottom(x).tickFormat(d3.timeFormat("%Y")))
        .selectAll("text")
        .style("font-size", "12px")
        .style("font-family", "'Open Sans', sans-serif");

    svg.append("g")
        .call(d3.axisLeft(y))
        .selectAll("text")
        .style("font-size", "12px")
        .style("font-family", "'Open Sans', sans-serif");

    // Y-axis arrows and labels
    // Arrow pointing up with "more rubble/construction"
    svg.append("line")
        .attr("x1", -70)
        .attr("y1", 20)
        .attr("x2", -70)
        .attr("y2", 0)
        .attr("stroke", "#333")
        .attr("stroke-width", 2)
        .attr("marker-end", "url(#arrow-up)");
    
    // Wrap "More rubble/construction" on two lines
    const upText = svg.append("text")
        .attr("x", -80)
        .attr("text-anchor", "end")
        .style("font-size", "11px")
        .style("font-family", "'Open Sans', sans-serif")
        .style("fill", "#333");
    upText.append("tspan").attr("x", -80).attr("dy", 0).attr("y", 5).text("More rubble/");
    upText.append("tspan").attr("x", -80).attr("dy", 14).text("construction");
    
    // Arrow pointing down with "more flooded vegetation and water"
    svg.append("line")
        .attr("x1", -70)
        .attr("y1", height - 20)
        .attr("x2", -70)
        .attr("y2", height)
        .attr("stroke", "#333")
        .attr("stroke-width", 2)
        .attr("marker-end", "url(#arrow-down)");
    
    // Wrap "More flooded vegetation and water" on two lines
    const downText = svg.append("text")
        .attr("x", -80)
        .attr("text-anchor", "end")
        .style("font-size", "11px")
        .style("font-family", "'Open Sans', sans-serif")
        .style("fill", "#333");
    downText.append("tspan").attr("x", -80).attr("y", height - 18).text("More flooded vegetation");
    downText.append("tspan").attr("x", -80).attr("dy", 14).text("and water");

    // Define arrow markers
    svg.append("defs").selectAll("marker")
        .data(["arrow-up", "arrow-down"])
        .enter().append("marker")
        .attr("id", d => d)
        .attr("viewBox", "0 -5 10 10")
        .attr("refX", 5)
        .attr("refY", 0)
        .attr("markerWidth", 10)
        .attr("markerHeight", 10)
        .attr("orient", "auto")
        .append("path")
        .attr("d", "M0,-5L10,0L0,5")
        .attr("fill", "#333");

    // Add axis labels removed - no 'Date' on x-axis

    // Add y-axis label
    svg.append("text")
        .attr("text-anchor", "middle")
        .attr("transform", "rotate(-90)")
        .attr("y", -45)
        .attr("x", -height / 2)
        .style("font-size", "13px")
        .style("font-weight", "600")
        .style("font-family", "'Open Sans', sans-serif")
        .style("fill", "#333")
        .text("Backscatter Intensity");

    // Add title above the images
    const imagesOffsetX = -(chartOffsetX - margin.left);
    svg.append("text")
        .attr("x", imagesOffsetX)
        .attr("y", -310)
        .attr("text-anchor", "start")
        .style("font-size", "18px")
        .style("font-weight", "700")
        .style("font-family", "'Open Sans', sans-serif")
        .style("fill", "#333")
        .text(`Monitoring the Construction of ${data.name} Dam, Shan State`);

    // Add timeline images positioned above the chart
    if (metadata.timeline_images && metadata.timeline_images.length > 0) {
        // All images same size
        const imgSize = 240;
        const imageRowY = -imgSize - 40; // Position above the chart
        const spacing = 10;
        // Center images: offset from chart center
        const imagesStartX = -(chartOffsetX - margin.left);
        
        metadata.timeline_images.forEach((img, idx) => {
            const imgDate = new Date(img.date);
            const xPos = x(imgDate);

            // Calculate image position - place them next to each other
            const imgX = imagesStartX + idx * (imgSize + spacing);

            // Add image as square (no border)
            svg.append("image")
                .attr("xlink:href", img.image_url)
                .attr("x", imgX)
                .attr("y", imageRowY)
                .attr("width", imgSize)
                .attr("height", imgSize)
                .attr("cursor", "pointer")
                .style("opacity", 0.9)
                .on("click", function() {
                    showImageModal(img.image_url, img.label);
                })
                .on("mouseover", function() {
                    d3.select(this).style("opacity", 1).style("filter", "brightness(1.1)");
                })
                .on("mouseout", function() {
                    d3.select(this).style("opacity", 0.9).style("filter", "brightness(1)");
                })
                .append("title")
                .text(img.label);

            // Add year label above the image
            svg.append("text")
                .attr("x", imgX + imgSize / 2)
                .attr("y", imageRowY - 10)
                .attr("text-anchor", "middle")
                .style("font-size", "13px")
                .style("font-weight", "600")
                .style("font-family", "'Open Sans', sans-serif")
                .style("fill", "#333")
                .text(img.label);
        });
    }

    // Create line generator for trend
    const trendLine = d3.line()
        .x(d => x(d.date))
        .y(d => y(d.trend));

    // Add trend line ON TOP of images
    svg.append("path")
        .datum(chartData)
        .attr("fill", "none")
        .attr("stroke", "#333")
        .attr("stroke-width", 3)
        .attr("d", trendLine);

    // Add source text at bottom
    svg.append("text")
        .attr("x", imagesOffsetX)
        .attr("y", height + 40)
        .attr("text-anchor", "start")
        .style("font-size", "13px")
        .style("font-family", "'Open Sans', sans-serif")
        .style("fill", "#666")
        .text("Source: Analysis conducted using SAR data from Sentinel-1A; reference images from LANDSAT, Google Earth and Sentinel-2 accessed using Google Earth Engine.");

    // Add interpretation text below source (only for Upper Yeywa)
    if (damId === 'upper_yeywa') {
        svg.append("text")
            .attr("x", imagesOffsetX)
            .attr("y", height + 70)
            .attr("text-anchor", "start")
            .style("font-size", "12px")
            .style("font-family", "'Open Sans', sans-serif")
            .style("fill", "#333")
            .text("2019\u20132021: potential period of construction");

        svg.append("text")
            .attr("x", imagesOffsetX)
            .attr("y", height + 88)
            .attr("text-anchor", "start")
            .style("font-size", "12px")
            .style("font-family", "'Open Sans', sans-serif")
            .style("fill", "#333")
            .text("2023\u20132025: potential pause/completion of construction phase");
    }

    // Add annotation markers
    if (data.annotations && data.annotations.length > 0) {
        data.annotations.forEach((ann, i) => {
            const annDate = new Date(ann.date);
            const xPos = x(annDate);

            // Add vertical line
            svg.append("line")
                .attr("x1", xPos)
                .attr("x2", xPos)
                .attr("y1", 0)
                .attr("y2", height)
                .attr("stroke", "#999")
                .attr("stroke-width", 1)
                .attr("stroke-dasharray", "4,4")
                .attr("opacity", 0.6);

            // Add annotation text to the right of the line
            const lines = ann.text.split('\n');
            const textGroup = svg.append("g")
                .attr("transform", `translate(${xPos + 8}, ${20 + i * 30})`);

            lines.forEach((line, lineIndex) => {
                textGroup.append("text")
                    .attr("text-anchor", "start")
                    .attr("y", lineIndex * 14)
                    .style("font-size", "11px")
                    .style("font-family", "'Open Sans', sans-serif")
                    .style("fill", "#333")
                    .style("font-weight", "600")
                    .text(line);
            });
        });
    }
}

// Function to show image modal
function showImageModal(imageUrl, label) {
    const modal = document.getElementById('imageModal');
    const modalImg = document.getElementById('modalImage');
    const caption = document.getElementById('caption');

    modal.style.display = "block";
    modalImg.src = imageUrl;
    caption.textContent = label;
}

// Function to close modal
function closeModal() {
    document.getElementById('imageModal').style.display = "none";
}

// Tab switching functionality
function switchTab(damId) {
    // Hide all dam sections
    document.querySelectorAll('.dam-section').forEach(section => {
        section.classList.remove('active');
    });

    // Remove active class from all tabs
    document.querySelectorAll('.tab-button').forEach(tab => {
        tab.classList.remove('active');
    });

    // Show selected dam section
    document.getElementById(damId).classList.add('active');

    // Add active class to the button that was clicked
    const clickedButton = Array.from(document.querySelectorAll('.tab-button')).find(btn => 
        btn.getAttribute('onclick').includes(damId)
    );
    if (clickedButton) {
        clickedButton.classList.add('active');
    }

    // Create chart for selected dam
    createChart(damId);
}

